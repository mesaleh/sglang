_HASH_DOMAIN = b"sglang-dflash-draft-snapshot-v1\0"
_TELEMETRY_PREFIX = "DFLASH_SNAPSHOT_TELEMETRY "
_DEFAULT_MIN_PREFIX_LENGTH = 10_208
logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class DFlashDraftSnapshotConfig:
    ring: DFlashDraftRingConfig
    min_prefix_length: int
    snapshot_rows: int
    physical_slots: int
    service_slots: int
    snapshot_base: int
    pool_size: int
    padded_tokens: int

    def slot_base(self, slot: int) -> int:
        slot = int(slot)
        if slot < 0 or slot >= self.physical_slots:
            raise ValueError(
                f"snapshot slot is outside [0, {self.physical_slots}): {slot}"
            )
        return self.snapshot_base + slot * self.snapshot_rows


def build_dflash_draft_snapshot_config(
    ring: DFlashDraftRingConfig,
    *,
    min_prefix_length: int = _DEFAULT_MIN_PREFIX_LENGTH,
    physical_slots: int = 21,
    service_slots: int = 20,
) -> DFlashDraftSnapshotConfig:
    min_prefix_length = int(min_prefix_length)
    physical_slots = int(physical_slots)
    service_slots = int(service_slots)
    if min_prefix_length <= 0 or min_prefix_length % int(ring.page_size):
        raise ValueError(
            "min_prefix_length must be positive and page aligned: "
            f"prefix={min_prefix_length}, page={ring.page_size}"
        )
    if physical_slots <= 0:
        raise ValueError("physical_slots must be positive")
    if service_slots <= 0 or service_slots >= physical_slots:
        raise ValueError(
            "service_slots must be positive and leave a publication reserve: "
            f"service={service_slots}, physical={physical_slots}"
        )

    # A radix snapshot is published at a page-aligned boundary. At that exact
    # boundary the compact suffix is ceil(window/page)*page; the later
    # non-aligned residue is regenerated by ordinary prefill.
    snapshot_rows = (
        (int(ring.window_size) + int(ring.page_size) - 1) // int(ring.page_size)
    ) * int(ring.page_size)
    snapshot_base = int(ring.padded_tokens)
    padded_tokens = snapshot_base + physical_slots * snapshot_rows
    pool_size = padded_tokens - int(ring.page_size)
    return DFlashDraftSnapshotConfig(
        ring=ring,
        min_prefix_length=min_prefix_length,
        snapshot_rows=snapshot_rows,
        physical_slots=physical_slots,
        service_slots=service_slots,
        snapshot_base=snapshot_base,
        pool_size=pool_size,
        padded_tokens=padded_tokens,
    )


@dataclass(frozen=True, order=True)
class DFlashSnapshotKey:
    prefix_length: int
    digest: bytes


@dataclass(frozen=True)
class DFlashSnapshotHandle:
    key: DFlashSnapshotKey
    slot: int
    slot_generation: int
    cache_generation: int
    valid_rows: int


@dataclass(frozen=True)
class DFlashSnapshotPublication:
    key: DFlashSnapshotKey
    handle: DFlashSnapshotHandle | None
    victim: DFlashSnapshotHandle | None
    action: str
    reason: str | None = None

    @property
    def copy_required(self) -> bool:
        return self.action == "copy"


